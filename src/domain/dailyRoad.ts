/**
 * Дневной переход (замена сердечек дневной цели): цель дня — путь от утренней стоянки до привала. Четыре придорожных
 * фонаря делят его на пять частей, как прежние пять сердец; у пройденного фонаря загорается огонь, у цели загорается
 * костёр привала. Огонёк стрика рядом — число ночей подряд у костра.
 */

/** Придорожные фонари — доли цели дня (до 2.109.2 это были верстовые камни). */
export const ROAD_LAMPS = [0.2, 0.4, 0.6, 0.8] as const;

export interface RoadState {
  /** Пройденная доля пути, 0–1. */
  ratio: number;
  /** Горит ли каждый фонарь: путник его прошёл. */
  lamps: boolean[];
  /** Путник у костра: цель дня выполнена. */
  camp: boolean;
}

export function roadState(xp: number, goal: number): RoadState {
  const ratio = goal > 0 ? Math.min(1, Math.max(0, xp / goal)) : 0;
  return { ratio, lamps: ROAD_LAMPS.map((s) => ratio >= s), camp: ratio >= 1 };
}
